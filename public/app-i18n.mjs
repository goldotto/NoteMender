// English resolution stays in one place so both the English and Japanese paths
// share the same fallback behaviour.
function englishText(value){
 if(known.has(value))return known.get(value);
 for(const [pattern,format] of patterns)if(pattern.test(value))return value.replace(pattern,format);
 return value;
}
export function appText(value){
 if(typeof value!=='string')return value;
 const current=getLanguage();
 if(current==='ja'){
  if(JA_TEXT[value]!==undefined)return JA_TEXT[value];
  for(const [pattern,format] of patternsJa)if(pattern.test(value))return value.replace(pattern,format);
  // Untranslated dynamic text falls back to English rather than Chinese.
  return englishText(value);
 }
 if(current!=='en')return value;
 return englishText(value);
}
