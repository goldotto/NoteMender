const TIMBRE_EN={classic:'Piano-style synthesis',soft:'Soft synthesis',bright:'Bright synthesis',pluck:'Plucked synthesis',flute:'Flute-style synthesis',strings:'String-style synthesis',acoustic_grand_piano:'Piano',acoustic_guitar_nylon:'Nylon-string guitar',violin:'Violin',piano:'Piano',guitar:'Nylon-string guitar'};
const TIMBRE_JA={classic:'ピアノ風の合成音',soft:'ソフトな合成音',bright:'明るい合成音',pluck:'撥弦風の合成音',flute:'フルート風の合成音',strings:'ストリングス風の合成音',acoustic_grand_piano:'ピアノ',acoustic_guitar_nylon:'ナイロン弦ギター',violin:'ヴァイオリン',piano:'ピアノ',guitar:'ナイロン弦ギター',flute:'フルート'};
export function timbreName(t){
 const current=getLanguage();
 if(current==='en')return t.instrument?({piano:'Piano',guitar:'Nylon-string guitar',flute:'Flute',violin:'Violin'}[t.id]||t.name):(TIMBRE_EN[t.id]||t.name);
 if(current==='ja')return t.instrument?({piano:'ピアノ',guitar:'ナイロン弦ギター',flute:'フルート',violin:'ヴァイオリン'}[t.id]||t.name):(TIMBRE_JA[t.id]||t.name);
 return t.name;
}
